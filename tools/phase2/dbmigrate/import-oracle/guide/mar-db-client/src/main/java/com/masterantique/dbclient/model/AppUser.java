package com.masterantique.dbclient.model;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Lob;
import jakarta.persistence.Table;
import java.time.LocalDateTime;

/**
 * One row of {@code users}. The legacy table holds customers, employees and managers together (the
 * {@code discriminator} column says which); here it is a plain column, so one entity reads all of them.
 * Named AppUser because "User" clashes with many framework classes.
 */
@Entity
@Table(name = "users")
public class AppUser {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)   // GENERATED BY DEFAULT AS IDENTITY
    private Integer id;

    @Column(name = "name", nullable = false, length = 256)
    private String name;                                  // stored as typed; unique ignoring case among active users

    @Column(name = "created_at", nullable = false)
    private LocalDateTime createdAt;                      // TIMESTAMP(3), no time zone

    @Lob
    @Column(name = "password_hash")
    private String passwordHash;                          // CLOB; NULL for every migrated user (sanitized)

    @Column(name = "discriminator", nullable = false, length = 128)
    private String discriminator;                         // Customer | Employee | Manager

    @Column(name = "deleted_at")
    private LocalDateTime deletedAt;                      // soft delete: NULL = active

    @Column(name = "email", length = 256)
    private String email;

    @Column(name = "email_confirmed", nullable = false)
    private boolean emailConfirmed;                       // BOOLEAN (Oracle 23ai and later)

    @Lob
    @Column(name = "security_stamp")
    private String securityStamp;

    @Lob
    @Column(name = "phone_number")
    private String phoneNumber;

    @Column(name = "phone_number_confirmed", nullable = false)
    private boolean phoneNumberConfirmed;

    @Column(name = "two_factor_enabled", nullable = false)
    private boolean twoFactorEnabled;

    @Column(name = "lockout_end_date_utc")
    private LocalDateTime lockoutEndDateUtc;

    @Column(name = "lockout_enabled", nullable = false)
    private boolean lockoutEnabled;

    @Column(name = "access_failed_count", nullable = false)
    private int accessFailedCount;

    @Column(name = "must_reset_password", nullable = false)
    private boolean mustResetPassword;                    // true for every migrated user

    protected AppUser() {
    }

    public Integer getId() { return id; }
    public String getName() { return name; }
    public LocalDateTime getCreatedAt() { return createdAt; }
    public String getPasswordHash() { return passwordHash; }
    public String getDiscriminator() { return discriminator; }
    public LocalDateTime getDeletedAt() { return deletedAt; }
    public String getEmail() { return email; }
    public boolean isMustResetPassword() { return mustResetPassword; }
    public int getAccessFailedCount() { return accessFailedCount; }

    /** Called only after a successful first-login password change. */
    public void setNewPassword(String hash, String newSecurityStamp) {
        this.passwordHash = hash;
        this.securityStamp = newSecurityStamp;
        this.mustResetPassword = false;
        this.accessFailedCount = 0;
    }
}
